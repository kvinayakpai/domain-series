"""The four Store 014 questions on Gemini, five conditions. Usage: run.py OUTDIR CONDITION"""
import json, os, re, sys, time
from pathlib import Path
import psycopg2, requests

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "public/data/auto-ontology"
BASE = "https://generativelanguage.googleapis.com/v1beta/openai"
KEY = os.environ["GEMINI_API_KEY"]
MODEL = os.environ["MODEL"]

def ttl(n): return f"=== ONTOLOGY (OWL, Turtle) ===\n{(D/f'store014-{n}-ontology.ttl').read_text()}\n\n=== SHACL SHAPES (Turtle) ===\n{(D/f'store014-{n}-shapes.ttl').read_text()}"
CONDITIONS = {
    "schema": ("", ""),
    "autoont": ("Here is the output of an automatic ontology tool (draft terms and definitions for this database). Use it as you see fit:\n\n", lambda: (D/"store014-draft-terms.json").read_text()),
    "ontop": ("Here is an OWL ontology generated by Ontop from the database. Use it as you see fit:\n\n", lambda: (D/"store014-ontop-ontology.owl").read_text()),
    "sonnet": ("Here is an ontology of the business and the database, as OWL and SHACL files. Use it as you see fit:\n\n", lambda: ttl("sonnet")),
    "opus": ("Here is an ontology of the business and the database, as OWL and SHACL files. Use it as you see fit:\n\n", lambda: ttl("opus")),
}
INTRO = ("You are a data analyst agent for a grocery store (Store 014, India). Answer the questions below using the Postgres database, "
         "with read-only SQL, the way a text-to-SQL agent would. Call the run_sql tool to run a query (tables live in the schemas store, "
         "warehouse and payments; explore the schema yourself as you need).\n\nUse only the run_sql tool and the material in this message.\n\n")
QUESTIONS = (
    "\n\nQUESTIONS\n1. How many bags of 5 kg atta were sold in June 2026?\n2. How many shoppers left without 5 kg atta in June 2026?\n"
    "3. What was on-shelf availability for 5 kg atta in June 2026?\n4. What were the lost sales of 5 kg atta in June 2026?\n\n"
    "For each question give: the SQL you ran (or \"none\"), your answer, and one line on how sure you are and what the answer is based on. "
    "If the records cannot answer a question, say so plainly instead of guessing. End with a JSON block:\n"
    '{"answers":[{"id":1,"sql":"...","answer":"...","basis":"..."}, ... 4 items]}')
TOOL = [{"type": "function", "function": {"name": "run_sql", "description": "Run one read-only SQL query on the Store 014 database and return the rows.",
         "parameters": {"type": "object", "properties": {"query": {"type": "string"}}, "required": ["query"]}}}]

def sql(q):
    try:
        con = psycopg2.connect(dbname="store014", options="-c default_transaction_read_only=on -c statement_timeout=30000")
        with con, con.cursor() as cur:
            cur.execute(q); rows = cur.fetchmany(60)
            out = "\n".join("|".join("" if v is None else str(v) for v in r) for r in rows)
        con.close(); return out[:4000] or "(no rows)"
    except Exception as e:
        return f"ERROR: {str(e)[:500]}"

class Blocked(Exception): pass

def chat(messages):
    last = ""
    for attempt in range(8):
        r = requests.post(f"{BASE}/chat/completions", timeout=600, headers={"Authorization": f"Bearer {KEY}"},
                          json={"model": MODEL, "messages": messages, "tools": TOOL, "max_tokens": 16000})
        if r.status_code < 300:
            return r.json()["choices"][0]["message"]
        last = f"{r.status_code} {r.text}"          # full body kept
        if r.status_code == 429 and "limit: 0" in r.text:
            raise Blocked(last)                      # a zero quota will not clear by waiting
        time.sleep(30 if r.status_code == 429 else 20)
    raise RuntimeError("model call failed 8 times: " + last)

def main():
    out = Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True); cond = sys.argv[2]
    head, body = CONDITIONS[cond]
    prompt = INTRO + (head + body() if body else "") + QUESTIONS
    messages = [{"role": "user", "content": prompt}]
    calls, final, started, err = [], "", time.time(), ""
    try:
        for _ in range(30):
            msg = chat(messages)
            messages.append({k: v for k, v in msg.items() if k in ("role", "content", "tool_calls") and v is not None})
            if not msg.get("tool_calls"):
                final = msg.get("content") or ""; break
            for tc in msg["tool_calls"]:
                try: q = json.loads(tc["function"]["arguments"]).get("query", "")
                except Exception: q = ""
                res = sql(q); calls.append({"sql": q, "result": res[:600]})
                messages.append({"role": "tool", "tool_call_id": tc["id"], "content": res})
    except Exception as e:
        err = str(e)
    rec = {"model": MODEL, "condition": cond, "prompt_chars": len(prompt), "seconds": round(time.time()-started),
           "sql_calls": calls, "final": final, "error": err}
    (out / f"{cond}.json").write_text(json.dumps(rec, indent=2))
    print(cond, "done", rec["seconds"], "s", err[:300])

main()
